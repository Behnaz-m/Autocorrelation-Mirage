#!/usr/bin/env python
"""Paired 2x2 mechanism ablation for episode memorization.

The factorial design switches the episode random-effect variance and the
episode-specific temporal/event-time mechanism independently.  ``temporal``
uses the main DGP's AR(1) state and its hazard link; when off, both are zero.
Each replicate generates one panel and evaluates the same boosted-tree model
with grouped and shuffled row-wise CV, making their AUROC difference paired.
The output is resumable: completed (condition, seed, split) records are kept.
"""

from __future__ import annotations

import argparse
import time
from pathlib import Path
import sys

import numpy as np
import pandas as pd
from scipy import stats

sys.path.insert(0, str(Path(__file__).parent.parent))

from src.data_generation import generate_panel_data, get_feature_columns, prepare_modeling_data
from src.evaluation import compute_pooled_oof_metrics, evaluate_grouped_cv, evaluate_random_cv


CONDITIONS = (
    (False, False, 0.0, 0.0, 0.0),
    (False, True, 0.0, 0.7, 0.15),
    (True, False, 0.5, 0.0, 0.0),
    (True, True, 0.5, 0.7, 0.15),
)


def _ci(values: pd.Series) -> tuple[float, float]:
    values = values.dropna().to_numpy(dtype=float)
    if len(values) < 2:
        return np.nan, np.nan
    se = values.std(ddof=1) / np.sqrt(len(values))
    critical = stats.t.ppf(0.975, df=len(values) - 1)
    mean = values.mean()
    return mean - critical * se, mean + critical * se


def summarize(records: pd.DataFrame) -> pd.DataFrame:
    good = records.loc[records.status == "ok"].copy()
    wide = good.pivot_table(
        index=["replicate", "seed", "episode_heterogeneity", "temporal_structure"],
        columns="split_method", values="auroc", aggfunc="first",
    ).reset_index()
    prevalence = good.groupby(
        ["replicate", "seed", "episode_heterogeneity", "temporal_structure"], as_index=False
    ).event_prevalence.first()
    wide = wide.merge(prevalence, on=["replicate", "seed", "episode_heterogeneity", "temporal_structure"])
    wide["delta_cv"] = wide["row_wise"] - wide["grouped"]
    rows = []
    for (heterogeneity, temporal), group in wide.groupby(["episode_heterogeneity", "temporal_structure"]):
        lo, hi = _ci(group.delta_cv)
        rows.append({
            "episode_heterogeneity": heterogeneity,
            "temporal_structure": temporal,
            "successful_replicates": len(group),
            "grouped_auroc_mean": group.grouped.mean(),
            "row_wise_auroc_mean": group.row_wise.mean(),
            "delta_cv_mean": group.delta_cv.mean(),
            "delta_cv_ci_lower": lo,
            "delta_cv_ci_upper": hi,
            "event_prevalence_mean": group.event_prevalence.mean(),
        })
    return pd.DataFrame(rows).sort_values(["episode_heterogeneity", "temporal_structure"])


def write_latex(summary: pd.DataFrame, target: Path) -> None:
    target.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "% Generated by experiments/run_mechanism_ablation.py; do not edit manually.",
        "\\begin{tabular}{llcccc}",
        "\\toprule",
        "Episode effect & Temporal state & Grouped & Row-wise & $\\Delta_{\\mathrm{CV}}$ (95\\% CI) & Prev. \\\\",
        "\\midrule",
    ]
    for row in summary.itertuples(index=False):
        yes_no = lambda value: "on" if value else "off"
        lines.append(
            f"{yes_no(row.episode_heterogeneity)} & {yes_no(row.temporal_structure)} & "
            f"{row.grouped_auroc_mean:.3f} & {row.row_wise_auroc_mean:.3f} & "
            f"{row.delta_cv_mean:.3f} [{row.delta_cv_ci_lower:.3f}, {row.delta_cv_ci_upper:.3f}] & "
            f"{row.event_prevalence_mean:.3f} \\\\")
    lines.extend(["\\bottomrule", "\\end{tabular}"])
    target.write_text("\n".join(lines) + "\n")


def run(n_replicates: int, start_seed: int, output: Path, summary_output: Path, latex_output: Path) -> pd.DataFrame:
    output.parent.mkdir(parents=True, exist_ok=True)
    records = pd.read_csv(output) if output.exists() else pd.DataFrame()
    required = {"replicate", "seed", "episode_heterogeneity", "temporal_structure", "split_method"}
    completed = set()
    if required.issubset(records.columns):
        completed = set(records.loc[records.status == "ok", list(required)].itertuples(index=False, name=None))
    rows = []
    for heterogeneity, temporal, alpha_std, ar_coef, hazard_coef in CONDITIONS:
        for replicate in range(n_replicates):
            seed = start_seed + replicate
            expected = [(replicate, seed, heterogeneity, temporal, split) for split in ("grouped", "row_wise")]
            if all(key in completed for key in expected):
                continue
            started = time.perf_counter()
            try:
                panel = generate_panel_data(
                    n_episodes=30, T_max=60, alpha_std=alpha_std, ar_coef=ar_coef,
                    hazard_coef=hazard_coef, noise_std=0.3, base_hazard=-3.0,
                    horizon=14, seed=seed,
                )
                X, y, groups = prepare_modeling_data(panel, get_feature_columns(panel))
                outcomes = {
                    "grouped": evaluate_grouped_cv(X, y, groups, n_splits=5),
                    "row_wise": evaluate_random_cv(X, y, n_splits=5, seed=seed, groups=groups),
                }
                for split, result in outcomes.items():
                    if (replicate, seed, heterogeneity, temporal, split) not in completed:
                        rows.append({
                            "replicate": replicate, "seed": seed,
                            "episode_heterogeneity": heterogeneity, "temporal_structure": temporal,
                            "split_method": split, "model": "boosted_trees",
                            "event_prevalence": float(y.mean()),
                            "auroc": compute_pooled_oof_metrics(result)["auc"], "status": "ok",
                            "runtime_seconds": time.perf_counter() - started,
                        })
            except Exception as exc:  # Preserve failures rather than silently discarding them.
                for split in ("grouped", "row_wise"):
                    if (replicate, seed, heterogeneity, temporal, split) not in completed:
                        rows.append({
                            "replicate": replicate, "seed": seed,
                            "episode_heterogeneity": heterogeneity, "temporal_structure": temporal,
                            "split_method": split, "model": "boosted_trees", "event_prevalence": np.nan,
                            "auroc": np.nan, "status": f"failed: {type(exc).__name__}: {exc}",
                            "runtime_seconds": time.perf_counter() - started,
                        })
    if rows:
        records = pd.concat([records, pd.DataFrame(rows)], ignore_index=True)
        records.to_csv(output, index=False)
    summary = summarize(records)
    summary_output.parent.mkdir(parents=True, exist_ok=True)
    summary.to_csv(summary_output, index=False)
    write_latex(summary, latex_output)
    return summary


def main() -> None:
    parser = argparse.ArgumentParser(description="Run resumable 2x2 mechanism ablation")
    parser.add_argument("--n-replicates", type=int, default=30)
    parser.add_argument("--start-seed", type=int, default=42)
    parser.add_argument("--output", type=Path, default=Path("results/camera_ready/mechanism_ablation.csv"))
    parser.add_argument("--summary-output", type=Path, default=Path("results/camera_ready/mechanism_ablation_summary.csv"))
    parser.add_argument("--latex-output", type=Path, default=Path("generated/mechanism_ablation_table.tex"))
    args = parser.parse_args()
    print(run(args.n_replicates, args.start_seed, args.output, args.summary_output, args.latex_output).to_string(index=False))


if __name__ == "__main__":
    main()
